// Update 8 Sect files
for (const [filename, archList] of Object.entries(sectArchitectures)) {
  const filePath = path.join(sectDir, filename);
  if (!fs.existsSync(filePath)) continue;
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace 组织架构 block
  const archBlock = '  组织架构:\n    层级划分:\n' + archList.map(item => '      - ' + item).join('\n') + '\n\n';
  content = content.replace(/  组织架构:[\s\S]*?(?=  核心功法传承:)/, archBlock);
  fs.writeFileSync(filePath, content, 'utf8');
  console.log('Updated sect:', filename);
}

